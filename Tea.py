# count letters in text
text = 'Выпей чая да отведай этих мягких французкий булок'
alp = ['а', 'б', 'в', 'г', 'д', 'е', 'ё', 'ж', 'з', 'и', 'й', 'к', 'л', 'м', 'н', 'о', 'п', 'р', 'с', 'т', 'у', 'ф', 'х', 'ц', 'ч', 'ш', 'щ', 'ъ', 'ы', 'ь', 'э', 'ю', 'я']
r = []
for i in alp:
    if text.count(i) != 0:
        r.append(f'В тексте ровно {text.count(i)} букв {i}')
print(r)
    